import zipfile, io
site = zipfile.ZipFile("scholaxia-website.zip")
names = site.namelist()
print("site files:", len(names))
print("index has 'offline school exams':", b"offline school exams" in site.read("index.html"))
print("student.html 'school exams' count:", site.read("student.html").count(b"school exams"))
print("downloads entries:", [n for n in names if n.startswith("downloads/")])
dz = zipfile.ZipFile(io.BytesIO(site.read("downloads/Scholaxia-Desktop-1.0.2-win64.zip")))
a = dz.read("ScholaxiaDesktop/resources/app/renderer/admin.html")
i = dz.read("ScholaxiaDesktop/resources/app/renderer/index.html")
au = dz.read("ScholaxiaDesktop/resources/app/renderer/js/auth.js")
bad = a.count(b"internal exam") + a.count(b"Internal Exa") + i.count(b"Internal Exa") + au.count(b"Internal Exa")
